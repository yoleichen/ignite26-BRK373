<#
.SYNOPSIS
    Creates app/ai-service/.env.cloud from your working .env, switching only the database settings
    to Azure SQL Database with Microsoft Entra ID.

.DESCRIPTION
    Keeps your AI provider, model settings, and calibrated retrieval threshold, so the deployed
    embeddings stay valid. Removes the local SQL login and password. Prints no setting values.

.EXAMPLE
    ./scripts/new-cloud-env.ps1 -Server casedesk-sql
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [ValidatePattern('^[A-Za-z0-9][A-Za-z0-9.-]*$')]
    [string] $Server,
    [string] $Database = 'CaseDesk',
    [string] $Source = (Join-Path $PSScriptRoot '../app/ai-service/.env'),
    [string] $Destination = (Join-Path $PSScriptRoot '../app/ai-service/.env.cloud'),
    [switch] $Force
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path $Source)) { throw "Missing $Source. Finish the local walkthrough steps first." }
if ((Test-Path $Destination) -and -not $Force) { throw "$Destination already exists. Pass -Force to replace it." }

$serverName = if ($Server.Contains('.')) { $Server } else { "$Server.database.windows.net" }
$sqlSettings = [ordered]@{
    SQL_SERVER                   = $serverName
    SQL_PORT                     = '1433'
    SQL_DATABASE                 = $Database
    SQL_AUTH                     = 'entra'
    SQL_TRUST_SERVER_CERTIFICATE = 'false'
}

$kept = Get-Content $Source | Where-Object { $_.Trim() -and $_ -notmatch '^\s*(#|SQL_)' }
$content = @('# Generated by scripts/new-cloud-env.ps1 from .env. Never commit this file.') +
    @($sqlSettings.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }) + $kept
Set-Content -Path $Destination -Value $content

Write-Host "Created $([IO.Path]::GetFullPath($Destination)) for $serverName/$Database with Microsoft Entra ID."
Write-Host 'AI provider, model settings, and RAG_MAX_DISTANCE were copied from .env.'
